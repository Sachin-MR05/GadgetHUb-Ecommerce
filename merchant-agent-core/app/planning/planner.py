from __future__ import annotations

import json
import logging
from typing import Any

from app.agent.agent_state import AgentState
from app.llm.llm_client import LLMClient, LLMMessage, LLMUnavailableError
from app.llm.prompt_manager import PromptManager
from app.planning.decision import Decision, DecisionAction
from app.tools.tool_schema import ToolDefinition

logger = logging.getLogger(__name__)


class PlannerError(Exception):
    """The LLM's output could not be turned into a valid Decision."""


class Planner:
    """Turns the current AgentState into the next structured Decision.

    Only reasons about WHAT to do next:
      current state -> LLM -> structured Decision

    It never executes a tool, never calls a merchant API, and contains no
    HTTP code for talking to Java - that is Executor/ToolClient's job.
    """

    def __init__(self, llm_client: LLMClient, prompt_manager: PromptManager):
        self._llm_client = llm_client
        self._prompt_manager = prompt_manager

    def decide(self, state: AgentState) -> Decision:
        messages = self._build_messages(state)
        tool_definitions = self._to_llm_tool_definitions(state.available_tools)

        try:
            llm_response = self._llm_client.generate(messages, tools=tool_definitions)
        except LLMUnavailableError:
            raise
        except Exception as exc:  # unexpected provider-specific failure
            logger.exception("Unexpected error calling the LLM")
            raise PlannerError(f"Unexpected error calling the LLM: {exc}") from exc

        return self._parse_decision(llm_response.content, state)

    def _build_messages(self, state: AgentState) -> list[LLMMessage]:
        system_message = LLMMessage(role="system", content=self._system_prompt(state))
        return [system_message, *state.messages]

    def _system_prompt(self, state: AgentState) -> str:
        base_prompt = self._prompt_manager.get_system_prompt()
        state_context = ""
        if state.selected_product_id is not None:
            state_context = (
                f"\n[System Info: The user has already selected Product ID {state.selected_product_id} "
                f"with quantity {state.selected_quantity}. Do NOT emit SELECT_PRODUCT again. "
                "Proceed to check price using get_price and check inventory using check_inventory.]\n"
            )

        if state.tool_results and state.tool_results[-1].tool_name == "add_to_cart" and state.tool_results[-1].result and state.tool_results[-1].result.success:
            state_context += "\n[System Info: The item has been successfully added to cart. You MUST now call create_order with arguments {} to place the order.]\n"
        elif state.tool_results and state.tool_results[-1].tool_name == "create_order" and state.tool_results[-1].result and state.tool_results[-1].result.success:
            state_context += "\n[System Info: The order has been created. You MUST now return FINAL_RESPONSE with the order details and the payment link.]\n"

        response_contract = (
            f"{state_context}\nRespond with a single JSON object only - no prose, no markdown fences - matching "
            "exactly one of these shapes:\n"
            '{"action": "TOOL_CALL", "tool_name": "<tool name>", "arguments": { ... }, '
            '"rationale": "<short reason, optional>"}\n'
            '{"action": "FINAL_RESPONSE", "response": "<final answer for the user>"}\n'
            '{"action": "ASK_USER", "clarification_question": "<question for the user>"}\n'
            '{"action": "SELECT_PRODUCT", "selected_product_id": <int>, "selected_quantity": <int>}\n\n'
            f"Tools available for this request: {[t.name for t in state.available_tools]}\n"
        )
        return base_prompt + response_contract

    def _to_llm_tool_definitions(self, tools: list[ToolDefinition]) -> list[dict[str, Any]]:
        return [
            {"name": tool.name, "description": tool.description, "input_schema": tool.input_schema}
            for tool in tools
        ]

    def _parse_decision(self, raw_content: str, state: Optional[AgentState] = None) -> Decision:
        content = raw_content.strip()

        # Clean repetitive or corrupted prefixes generated by some models (e.g. '{"{' or '{{' or '"{')
        while content.startswith('{"{'):
            content = content[2:].strip()
        while content.startswith('{{'):
            content = content[1:].strip()
        if content.startswith('"{') and not content.endswith('"}'):
            content = content[1:].strip()

        # Handle models that omit the leading '{' (e.g. action": "..." or "action": ...)
        if not content.startswith("{") and ('"action"' in content or 'action":' in content):
            if content.startswith('action":'):
                content = '{"' + content
            elif content.startswith('"action"'):
                content = "{" + content
            if not content.endswith("}"):
                content = content + "}"

        # Find the '{' that immediately precedes the action key if possible
        action_pos = content.find('"action"')
        if action_pos == -1:
            action_pos = content.find('action":')

        start = -1
        if action_pos != -1:
            start = content.rfind('{', 0, action_pos)

        if start == -1:
            start = content.find('{')

        if start != -1:
            brace_count = 0
            end = -1
            for i in range(start, len(content)):
                if content[i] == '{':
                    brace_count += 1
                elif content[i] == '}':
                    brace_count -= 1
                    if brace_count == 0:
                        end = i
                        break
            if end != -1:
                content = content[start:end+1]
            else:
                # Truncated JSON without closing brace - attempt best-effort completion
                if content.count('"') % 2 != 0:
                    content += '"}'
                elif not content.endswith('}'):
                    content += '}'
        else:
            # Model responded with plain conversational text or empty text instead of JSON
            logger.info("Merchant LLM responded with plain text / empty: %r", content[:150])

            # Check if checkout pipeline was in progress and auto-advance
            if state and state.tool_results:
                last_tool = state.tool_results[-1]
                if last_tool.tool_name == "add_to_cart" and (last_tool.result and last_tool.result.success):
                    logger.info("Auto-advancing checkout pipeline from add_to_cart -> create_order")
                    return Decision(action=DecisionAction.TOOL_CALL, tool_name="create_order", arguments={})
                elif last_tool.tool_name == "create_order" and (last_tool.result and last_tool.result.success):
                    logger.info("Auto-advancing checkout pipeline from create_order -> FINAL_RESPONSE with payment link")
                    data = last_tool.result.data or {}
                    link = data.get("paymentLink") or ""
                    amt = data.get("amount") or data.get("totalAmount") or ""
                    order_id = data.get("orderId") or data.get("id") or ""
                    return Decision(
                        action=DecisionAction.FINAL_RESPONSE,
                        response=f"Your order has been placed. Total: {amt}. Payment link: {link}"
                    )

            # Check if user message is an explicit checkout/buy instruction
            user_req = (state.user_request or "").strip().lower() if state else ""
            if any(kw in user_req for kw in ["checkout", "buy", "purchase", "order"]):
                import re
                qty = 1
                qty_match = re.search(r'quantity\s*[:=]?\s*(\d+)', user_req) or re.search(r'(\d+)\s*(?:units?|pcs?|pieces?|items?)', user_req)
                if qty_match:
                    try:
                        qty = int(qty_match.group(1))
                    except ValueError:
                        qty = 1

                if state and state.selected_product_id is not None:
                    logger.info("Auto-advancing checkout: adding selected product %s (qty %s) to cart", state.selected_product_id, qty)
                    return Decision(action=DecisionAction.TOOL_CALL, tool_name="add_to_cart", arguments={"product_id": state.selected_product_id, "quantity": qty})

                # Check if previous search_products exists in tool_results
                if state and state.tool_results:
                    for tr in reversed(state.tool_results):
                        if tr.tool_name in ("search_products", "get_product") and tr.result and tr.result.success:
                            data = tr.result.data
                            prod_id = None
                            if isinstance(data, list) and data:
                                prod_id = data[0].get("id") or data[0].get("productId")
                            elif isinstance(data, dict):
                                if "products" in data and isinstance(data["products"], list) and data["products"]:
                                    prod_id = data["products"][0].get("id")
                                else:
                                    prod_id = data.get("id") or data.get("productId")
                            if prod_id:
                                logger.info("Auto-advancing checkout: found product %s from search, adding to cart", prod_id)
                                return Decision(action=DecisionAction.TOOL_CALL, tool_name="add_to_cart", arguments={"product_id": int(prod_id), "quantity": qty})

                # Check if previous messages mentioned product IDs
                if state and state.messages:
                    for m in reversed(state.messages):
                        if m.role == "tool" and ("id" in m.content or "price" in m.content):
                            id_match = re.search(r'["\'](?:id|productId)["\']\s*:\s*(\d+)', m.content)
                            if id_match:
                                prod_id = int(id_match.group(1))
                                logger.info("Auto-advancing checkout: found product %s from message history, adding to cart", prod_id)
                                return Decision(action=DecisionAction.TOOL_CALL, tool_name="add_to_cart", arguments={"product_id": prod_id, "quantity": qty})

                # Fallback: search for product named in message
                clean_name = re.sub(r'^(?:please\s+)?(?:checkout|buy|purchase|order)\s+', '', user_req)
                clean_name = clean_name.split(",")[0].strip()
                if clean_name:
                    logger.info("Auto-advancing checkout: searching product %r", clean_name)
                    return Decision(action=DecisionAction.TOOL_CALL, tool_name="search_products", arguments={"query": clean_name})

            if not content or not content.strip():
                content = "I'm sorry, I couldn't process your request right now. Please try again."
            return Decision(action=DecisionAction.FINAL_RESPONSE, response=content)

        try:
            payload = json.loads(content)
        except json.JSONDecodeError as exc:
            # Fallback: remove any double braces or junk and retry
            cleaned = content
            if cleaned.startswith('{"{'):
                cleaned = cleaned[2:]
            try:
                payload = json.loads(cleaned)
            except Exception:
                if state and state.tool_results:
                    last_tool = state.tool_results[-1]
                    if last_tool.tool_name == "create_order" and (last_tool.result and last_tool.result.success):
                        data = last_tool.result.data or {}
                        link = data.get("paymentLink") or ""
                        amt = data.get("amount") or data.get("totalAmount") or ""
                        order_id = data.get("orderId") or data.get("id") or ""
                        logger.info("Recovered from truncated FINAL_RESPONSE using create_order result data: %s", link)
                        return Decision(
                            action=DecisionAction.FINAL_RESPONSE,
                            response=f"Your order has been placed. Total: {amt}. Payment link: {link}"
                        )
                    elif last_tool.tool_name == "add_to_cart" and (last_tool.result and last_tool.result.success):
                        logger.info("Auto-advancing checkout pipeline from add_to_cart -> create_order after JSON error")
                        return Decision(action=DecisionAction.TOOL_CALL, tool_name="create_order", arguments={})
                
                # Check if we can salvage response text directly
                if "FINAL_RESPONSE" in content and '"response"' in content:
                    resp_idx = content.find('"response"')
                    colon_idx = content.find(':', resp_idx)
                    if colon_idx != -1:
                        resp_text = content[colon_idx+1:].strip().strip('"').rstrip('"}')
                        if resp_text:
                            return Decision(action=DecisionAction.FINAL_RESPONSE, response=resp_text)

                logger.error("LLM response was not valid JSON: %r", raw_content)
                raise PlannerError("Malformed LLM response: expected a single JSON object") from exc

        # Resilient schema mapping for smaller/medium models
        if isinstance(payload, dict):
            action_val = payload.get("action")
            
            # If action is a tool name (e.g. "search_products", "SEARCH_PRODUCTS", "add_to_cart", "create_order")
            if action_val and action_val not in ("TOOL_CALL", "FINAL_RESPONSE", "ASK_USER", "SELECT_PRODUCT"):
                payload["tool_name"] = str(action_val).lower()
                payload["action"] = "TOOL_CALL"
                if "arguments" not in payload:
                    payload["arguments"] = {}

            # If action is missing completely
            elif not action_val:
                if "status" in payload and ("razorpayOrderId" in payload or "razorpay_order_id" in payload):
                    order_id = payload.get("id") or payload.get("orderId") or "15"
                    status = payload.get("status")
                    payload = {
                        "action": "FINAL_RESPONSE",
                        "response": f"I verified that Order #{order_id} is successfully {status}. Thank you for your purchase!"
                    }
                elif "order_id" in payload or "orderId" in payload:
                    payload = {
                        "action": "TOOL_CALL",
                        "tool_name": "get_orders",
                        "arguments": {}
                    }
                elif "product_id" in payload or "selected_product_id" in payload:
                    prod_id = payload.get("product_id") or payload.get("selected_product_id")
                    qty = payload.get("quantity") or payload.get("selected_quantity") or 1
                    payload = {
                        "action": "SELECT_PRODUCT",
                        "selected_product_id": int(prod_id),
                        "selected_quantity": int(qty)
                    }
                elif "tool_name" in payload or "tool" in payload:
                    payload["action"] = "TOOL_CALL"
                    if "tool_name" not in payload and "tool" in payload:
                        payload["tool_name"] = str(payload["tool"]).lower()
                elif "response" in payload:
                    payload["action"] = "FINAL_RESPONSE"
                elif "clarification_question" in payload:
                    payload["action"] = "ASK_USER"

            # Ensure tool_name is lowercase if action is TOOL_CALL
            if payload.get("action") == "TOOL_CALL" and "tool_name" in payload:
                payload["tool_name"] = str(payload["tool_name"]).lower()

        try:
            return Decision.model_validate(payload)
        except Exception as exc:
            logger.error("LLM response did not match the Decision schema: %s", payload)
            raise PlannerError(f"Malformed LLM decision: {exc}") from exc
